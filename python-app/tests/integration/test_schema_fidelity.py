"""Verifies every SQLAlchemy model matches the real (Flyway-created) schema by
reflecting the live database and diffing column names, and by round-tripping
one row per aggregate through the ORM. Run against a Postgres instance that
was seeded by replaying the actual V1-V17 Flyway SQL files (see python-app
Phase 1 notes) -- not a schema generated by Base.metadata.create_all."""

import uuid
